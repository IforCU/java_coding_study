#!/bin/sh
set -eu

project_root=$(CDPATH= cd -P "$(dirname "$0")/.." && pwd)
cd "$project_root"
restart=false
case "$#" in
    0) ;;
    1) if [ "$1" = --restart ]; then restart=true; else printf '%s\n' 'Usage: sh scripts/verify.sh [--restart]' >&2; exit 2; fi ;;
    *) printf '%s\n' 'Usage: sh scripts/verify.sh [--restart]' >&2; exit 2 ;;
esac

fail() {
    printf '[FAIL] %s\n' "$1" >&2
    printf '%s\n' 'Verification stopped. Containers and database data were preserved.' >&2
    exit 1
}
compose() {
    docker compose --profile phase0 "$@" || fail 'Compose command failed.'
}
database_query() {
    printf '%s\n' "$1" | docker compose --profile phase0 exec -T db sh -c 'exec psql -X -q -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d "$POSTGRES_DB" -t -A -F "|"'
}
ready_matches() {
    printf '%s\n' "$1" | grep -Eq '"status"[[:space:]]*:[[:space:]]*"UP"' &&
    printf '%s\n' "$1" | grep -Eq '"database"[[:space:]]*:[[:space:]]*"UP"' &&
    printf '%s\n' "$1" | grep -Eq '"schemaVersion"[[:space:]]*:[[:space:]]*1[[:space:]]*[,}]' &&
    printf '%s\n' "$1" | grep -Eq '"environment"[[:space:]]*:[[:space:]]*"local-learning"'
}
assert_ready() {
    response=$(curl -fsS --max-time 5 "$base_url/health/ready") || fail 'Readiness HTTP request failed.'
    ready_matches "$response" || fail 'Readiness response does not match the Phase 0 database contract.'
}

sh "$project_root/scripts/doctor.sh" || fail 'Environment check failed. Runtime verification was not started.'
command -v curl >/dev/null 2>&1 || fail 'curl is required for the HTTP checks.'
# The runtime image executes mvn verify during its build, including unit tests.
compose up --build -d --wait --wait-timeout 180
binding=$(compose port legacy 8080)
case "$binding" in
    127.0.0.1:*) port=${binding#127.0.0.1:} ;;
    *) fail 'Expected exactly one legacy HTTP port bound to 127.0.0.1.' ;;
esac
case "$port" in ''|*[!0-9]*) fail 'Invalid legacy HTTP port.' ;; esac
[ "$port" -ge 1 ] && [ "$port" -le 65535 ] || fail 'Invalid legacy HTTP port.'
base_url="http://127.0.0.1:$port"

home_response=$(curl -fsS --max-time 10 "$base_url/") || fail 'The JSP home page could not be loaded.'
printf '%s\n' "$home_response" | grep -Fq 'Hello World' || fail 'The rendered JSP home page did not contain Hello World.'
printf '%s\n' '[PASS] HTTP/JSP Hello World.'
live=$(curl -fsS --max-time 5 "$base_url/health/live") || fail 'Liveness HTTP request failed.'
printf '%s\n' "$live" | grep -Eq '"status"[[:space:]]*:[[:space:]]*"UP"' || fail 'Liveness response did not report UP.'
printf '%s\n' '[PASS] Liveness.'
assert_ready
printf '%s\n' '[PASS] Database readiness, schema version and environment.'

metadata_query="SELECT environment, schema_version, (SELECT count(*) FROM bootstrap.schema_history WHERE version = 1) FROM bootstrap.app_metadata WHERE environment = 'local-learning';"
before=$(database_query "$metadata_query") || fail 'Initial database verification query failed.'
[ "$before" = 'local-learning|1|1' ] || fail 'Initial database metadata is invalid.'
compose run --rm migrate
after=$(database_query "$metadata_query") || fail 'Database verification query failed after migration re-run.'
[ "$after" = "$before" ] || fail 'Migration re-run changed database metadata.'
assert_ready
printf '%s\n' '[PASS] Migration and seed re-run without changing metadata.'

if [ "$restart" = true ]; then
    # UUID is generated by PostgreSQL, so the host needs no UUID utility.
    marker=$(database_query "INSERT INTO bootstrap.verification_marker (marker_id) VALUES ('phase0-' || gen_random_uuid()::text) RETURNING marker_id;") || fail 'Persistence marker could not be inserted.'
    case "$marker" in phase0-*) ;; *) fail 'Invalid persistence marker.' ;; esac
    case "$marker" in *[!a-z0-9-]*) fail 'Invalid persistence marker.' ;; esac
    compose restart db
    compose restart legacy
    recovered=false
    attempt=0
    # At most 30 requests of <= 1 second and 29 sleeps of 1 second.
    while [ "$attempt" -lt 30 ]; do
        if response=$(curl -fsS --max-time 1 "$base_url/health/ready" 2>/dev/null) && ready_matches "$response"; then
            recovered=true
            break
        fi
        attempt=$((attempt + 1))
        if [ "$attempt" -lt 30 ]; then sleep 1; fi
    done
    [ "$recovered" = true ] || fail 'Database readiness did not recover within 60 seconds after restart.'
    retained=$(database_query "SELECT marker_id FROM bootstrap.verification_marker WHERE marker_id = '$marker';") || fail 'Persistence query failed after restart.'
    [ "$retained" = "$marker" ] || fail 'Persistence marker was not retained after restart.'
    printf '%s\n' '[PASS] DB and application restart; the inserted marker was retained.'
else
    printf '%s\n' '[NOT RUN] Restart and persistence check. Use --restart to include it.'
fi
printf '%s\n' 'Requested verification checks passed. Containers are left running.'
